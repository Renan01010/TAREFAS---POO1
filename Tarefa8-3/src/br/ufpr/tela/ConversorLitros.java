    private void botaoConverterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botaoConverterActionPerformed
            try {
                double litros = Double.parseDouble(campoLitros.getText());
                double galoes = litros / 3.785;
                resultado.setText(String.format("%.2f galões", galoes));
            } catch (NumberFormatException e) {
                resultado.setText("Digite um número válido!");
        }         
    }//GEN-LAST:event_botaoConverterActionPerformed

